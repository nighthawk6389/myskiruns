// (black unless rated). Winter's Way Ext. (circle 11 with a double diamond),
// West Sluice Chute (circle 20, no symbol: black, as its neighbours) and the
// back side's five chutes (circles 70-74 in the inset, no symbols: double
// black, as every Snowfields run the inset rates) have no line: markers.
// Elevation is the summit as printed. x/y/baseY/width are unused layout
