// diamond, and advanced intermediate (a blue square with a black diamond, its
// line blue under black dashes) is blue. Names are spelled as the trail report
// spells them (report.json: the mtnpowder feed); its ratings all agree with the
// map's. Chute 1, 2 and 3 and Triangle 3 take the number their group id
// carries. All Out ("closed to public") and the snowshoe trails (Duster,
// Chisholm Trail) are left out; the report's boundary gates aren't on the map.
