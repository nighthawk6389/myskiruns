// drawn on two or three panels). Names are as printed. Difficulty is the
// symbol printed with each name, plus the unnamed symbols Vail prints on a
// run's line where its rating changes; a run with several ratings takes the
// majority, the harder one on a tie (Born Free, Ledges, Northface Catwalk,
// Riva Ridge, Simba, Skid Road: blue; Bwana, Northstar, Safari, The
// Preserve: black; Cady's Cafe, Prima: double-black). No symbol printed: the
