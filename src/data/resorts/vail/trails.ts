// Feet and Upper Lion's Way take their line's colour (green); the two terrain
// parks (Golden Peak Terrain Park, Jake's Ride) seed_roster's default (blue).
// Names with no drawn line (open slopes, glades, bowls, parks) are markers at the
// name. Elevations are the highest printed on each panel. x/y/baseY/width are
// unused layout fields.
